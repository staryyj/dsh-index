def _qty_rows_from_boq(boq, limit=10):
    """把 boq.summarize 的结果转成工程量表行"""
    if not boq:
        return None
    order = ['拆除路面', '拆除基层', '旧板病害处理', '植筋', '防裂贴', '应力吸收层',
             '水泥稳定碎石基层', '级配碎石底基层', '沥青混凝土面层', '水泥混凝土路面',
             '人行道铺装', '拆除人行道', '侧平石', '雨水管', '污水管', '给水管', '再生水管',
             '检查井', '检查井加高', '雨水口', '通信排管', '路灯灯具', '绿化']
    rows = []
    for label in order:
        if label not in boq:
            continue
        parts = []
        for unit, val in boq[label].items():
            txt = f'{val:,.2f}'.rstrip('0').rstrip('.')
            parts.append(f'{txt}' if unit in ('项',) else f'{txt}')
        unit_txt = '/'.join(boq[label].keys())
        rows.append([str(len(rows) + 1), label, unit_txt, ' / '.join(parts), '按清单'])
        if len(rows) >= limit:
            break
    return rows or None


